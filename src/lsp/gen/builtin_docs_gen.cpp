const char *const *builtin_doc_languages(int *out_n) {
    if (out_n) *out_n = kLanguageCount;
    return kLanguages;
}

int builtin_doc_count() {
    return kEntryCount;
}

bool builtin_doc_at(int idx, BuiltinDocView *out) {
    if (idx < 0 || idx >= kEntryCount || out == nullptr) return false;
    const DocEntry &e = kEntries[idx];
    out->name = e.name;
    out->sig = e.sig;
    out->doc = e.doc;
    out->doc_count = kLanguageCount;
    return true;
}

bool builtin_doc_find(const char *name, BuiltinDocView *out) {
    if (name == nullptr || out == nullptr) return false;
    int lo = 0, hi = kEntryCount - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        const int c = std::strcmp(kEntries[mid].name, name);
        if (c == 0) return builtin_doc_at(mid, out);
        if (c < 0)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return false;
}

